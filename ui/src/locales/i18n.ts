export const locale = ref<'zh-Hans' | 'en'>('zh-Hans');

export function setLocale(value: string | null | undefined): void {
  locale.value = value === 'en' ? 'en' : 'zh-Hans';
  document.documentElement.lang = locale.value;
}

/** Looks up a message; unknown keys (e.g. a new host reason key) fall back to the key itself, never to HTML. */
export function t(key: string, params?: Record<string, string | number>): string {
  const table: Record<string, string> = locale.value === 'en' ? en : zh;
  let text = table[key] ?? key;
  if (params) for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

